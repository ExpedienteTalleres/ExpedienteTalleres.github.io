    var prevBtn = document.getElementById('carousel-prev');
    var nextBtn = document.getElementById('carousel-next');
    var dotsContainer = document.getElementById('carousel-dots');
    var counterEl = document.getElementById('carousel-counter');
    var currentIndex = 0;

    function getCardsPerView() {
      var w = window.innerWidth;
      if (w >= 1280) return 5;
      if (w >= 1024) return 4;
      if (w >= 768) return 3;
      if (w >= 480) return 2;
      return 1;
    }

    function getTotalPages() {
      var perView = getCardsPerView();
      return Math.ceil(presidentes.length / perView);
    }

    function updateCarousel() {
      var perView = getCardsPerView();
      var totalCards = presidentes.length;
      var maxIndex = Math.max(0, totalCards - perView);

      if (currentIndex > maxIndex) currentIndex = maxIndex;

      var gapPx = 20;
      var containerWidth = document.querySelector('.carousel-track-container').offsetWidth;
      var cardWidth = (containerWidth - (perView - 1) * gapPx) / perView;
      var offset = currentIndex * (cardWidth + gapPx);

      track.style.transform = 'translateX(-' + offset + 'px)';

      prevBtn.disabled = currentIndex <= 0;
      nextBtn.disabled = currentIndex >= maxIndex;

      updateDots();

      var lastVisible = Math.min(currentIndex + perView, totalCards);
      counterEl.innerHTML =
        '<span class="current-num">' + (currentIndex + 1) + ' - ' + lastVisible + '</span>' +
        ' / ' + totalCards;
    }

    function updateDots() {
      var perView = getCardsPerView();
      var totalPages = getTotalPages();
      var currentPage = Math.floor(currentIndex / perView);

      dotsContainer.innerHTML = '';

      var maxDots = 7;
      var startPage = 0;
      var endPage = totalPages;

      if (totalPages > maxDots) {
        startPage = Math.max(0, currentPage - Math.floor(maxDots / 2));
        endPage = startPage + maxDots;
        if (endPage > totalPages) {
          endPage = totalPages;
          startPage = endPage - maxDots;
        }
      }

      for (var i = startPage; i < endPage; i++) {
        var dot = document.createElement('button');
        dot.className = 'carousel-dot';
        if (i === currentPage) dot.classList.add('active');
        dot.setAttribute('aria-label', 'Pagina ' + (i + 1));
        dot.setAttribute('data-page', i);
        dot.addEventListener('click', function () {
          var page = parseInt(this.getAttribute('data-page'), 10);
          currentIndex = page * getCardsPerView();
          updateCarousel();
        });
        dotsContainer.appendChild(dot);
      }
    }

    prevBtn.addEventListener('click', function () {
      var perView = getCardsPerView();
      currentIndex = Math.max(0, currentIndex - perView);
      updateCarousel();
    });

    nextBtn.addEventListener('click', function () {
      var perView = getCardsPerView();
      var maxIndex = Math.max(0, presidentes.length - perView);
      currentIndex = Math.min(maxIndex, currentIndex + perView);
      updateCarousel();
    });

    var touchStartX = 0;
    var touchEndX = 0;
    var trackContainer = document.querySelector('.carousel-track-container');

    trackContainer.addEventListener('touchstart', function (e) {
      touchStartX = e.changedTouches[0].screenX;
    }, { passive: true });

    trackContainer.addEventListener('touchend', function (e) {
      touchEndX = e.changedTouches[0].screenX;
      var diff = touchStartX - touchEndX;
      if (Math.abs(diff) > 50) {
        if (diff > 0) {
          nextBtn.click();
        } else {
          prevBtn.click();
        }
      }
    }, { passive: true });

    document.addEventListener('keydown', function (e) {
      if (e.key === 'ArrowLeft') {
        prevBtn.click();
      } else if (e.key === 'ArrowRight') {
        nextBtn.click();
      }
    });

    var resizeTimer;
    window.addEventListener('resize', function () {
      clearTimeout(resizeTimer);
      resizeTimer = setTimeout(function () {
        updateCarousel();
      }, 150);
    });
