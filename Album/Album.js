        let currentYear = null;
        let currentPhotoIndex = 0;
        const decades = ['1910s', '1920s', '1930s', '1940s', '1950s', '1960s', '1970s', '1980s', '1990s', '2000s', '2010s', '2020s'];

        document.addEventListener('DOMContentLoaded', () => {
            generateFilters();
            renderYears(Object.keys(albumData).sort((a, b) => a - b));
            setupKeyboardNav();
        });

        function generateFilters() {
            const container = document.getElementById('decadeFilters');
            
            const allBtn = document.createElement('button');
            allBtn.className = 'filter-pill active';
            allBtn.textContent = 'Todos';
            allBtn.onclick = () => filterByDecade('all', allBtn);
            container.appendChild(allBtn);
            
            decades.forEach(decade => {
                const btn = document.createElement('button');
                btn.className = 'filter-pill';
                btn.textContent = decade;
                btn.onclick = () => filterByDecade(decade, btn);
                container.appendChild(btn);
            });
        }

        function renderYears(years) {
            const grid = document.getElementById('yearsGrid');
            const count = document.getElementById('resultsCount');
            grid.innerHTML = '';

            years.forEach(year => {
                const data = albumData[year];
                if (!data) return;

                const card = document.createElement('div');
                card.className = 'year-card';
                card.onclick = () => openGalleryModal(year);
                card.innerHTML = `
                    <div class="year-card-image">
                        <img src="${data.cover}" alt="Fotos de ${year}">
                    </div>
                    <div class="year-card-content">
                        <span class="year-card-year">${year}</span>
                        <span class="year-card-count">${data.photos.length} foto${data.photos.length !== 1 ? 's' : ''}</span>
                    </div>
                `;
                grid.appendChild(card);
            });
        }

        function filterByDecade(decade, btn) {
            document.querySelectorAll('.filter-pill').forEach(p => p.classList.remove('active'));
            btn.classList.add('active');

            if (decade === 'all') {
                renderYears(Object.keys(albumData).sort((a, b) => a - b));
                return;
            }

            const startYear = parseInt(decade);
            const endYear = startYear + 9;
            const filtered = Object.keys(albumData)
                .filter(y => y >= startYear && y <= endYear)
                .sort((a, b) => a - b);
            renderYears(filtered);
        }

        document.getElementById('yearSearch').addEventListener('input', function(e) {
            const value = e.target.value.trim();
            if (!value) {
                document.querySelector('.filter-pill').click();
                return;
            }

            document.querySelectorAll('.filter-pill').forEach(p => p.classList.remove('active'));
            const filtered = Object.keys(albumData)
                .filter(y => y.toString().includes(value))
                .sort((a, b) => a - b);
            renderYears(filtered);
        });

        function openGalleryModal(year) {
            currentYear = year;
            const data = albumData[year];
            
            document.getElementById('modalYear').textContent = year;
            document.getElementById('modalPhotoCount').textContent = `${data.photos.length} fotografia${data.photos.length !== 1 ? 's' : ''}`;
            
            const grid = document.getElementById('galleryGrid');
            grid.innerHTML = '';
            
            data.photos.forEach((photo, index) => {
                const item = document.createElement('div');
                item.className = 'gallery-item';
                item.onclick = () => openDetailModal(index);
                item.innerHTML = `
                    <div class="gallery-item-image">
                        <img src="${photo.url}" alt="${photo.title}">
                    </div>
                    <div class="gallery-item-info">
                        <h4>${photo.title}</h4>
                        <p>Click para ver detalles</p>
                    </div>
                `;
                grid.appendChild(item);
            });
            
            document.getElementById('galleryModal').classList.add('active');
            document.body.style.overflow = 'hidden';
        }

        function closeGalleryModal() {
            document.getElementById('galleryModal').classList.remove('active');
            document.body.style.overflow = '';
        }

        function openDetailModal(index) {
            currentPhotoIndex = index;
            updateDetailModal();
            document.getElementById('detailModal').classList.add('active');
        }

        function updateDetailModal() {
            const data = albumData[currentYear];
            const photo = data.photos[currentPhotoIndex];
            
            document.getElementById('detailImage').src = photo.url;
            document.getElementById('detailYear').textContent = `Año ${currentYear}`;
            document.getElementById('detailTitle').textContent = photo.title;
            document.getElementById('detailDescription').textContent = photo.description;
            document.getElementById('detailCounter').textContent = `Foto ${currentPhotoIndex + 1} de ${data.photos.length}`;
            
            document.getElementById('prevBtn').disabled = currentPhotoIndex === 0;
            document.getElementById('nextBtn').disabled = currentPhotoIndex === data.photos.length - 1;
        }

        function navigatePhoto(direction) {
            const data = albumData[currentYear];
            const newIndex = currentPhotoIndex + direction;
            
            if (newIndex >= 0 && newIndex < data.photos.length) {
                currentPhotoIndex = newIndex;
                updateDetailModal();
            }
        }

        function closeDetailModal() {
            document.getElementById('detailModal').classList.remove('active');
        }

        function setupKeyboardNav() {
            document.addEventListener('keydown', (e) => {
                if (document.getElementById('detailModal').classList.contains('active')) {
                    if (e.key === 'ArrowLeft') navigatePhoto(-1);
                    if (e.key === 'ArrowRight') navigatePhoto(1);
                    if (e.key === 'Escape') closeDetailModal();
                } else if (document.getElementById('galleryModal').classList.contains('active')) {
                    if (e.key === 'Escape') closeGalleryModal();
                }
            });
        }

        